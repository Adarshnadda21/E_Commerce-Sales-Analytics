/* Q14. Monthly Revenue Growth
Calculate monthly revenue and compare each month with the
previous month using LAG().
Show:
- month
- monthly_revenue
- previous_month_revenue
- revenue_change
- growth_percentage */
WITH cte AS (
    SELECT
        DATE_FORMAT(o.order_date, '%Y-%m') AS month,
        SUM(po.quantity * po.unit_price) AS monthly_revenue
    FROM orders o
    JOIN product_orders po
        ON o.order_id = po.order_id
    GROUP BY DATE_FORMAT(o.order_date, '%Y-%m')
),
growth AS (
    SELECT
        month,
        monthly_revenue,
        LAG(monthly_revenue) OVER (
            ORDER BY month
        ) AS previous_month_revenue
    FROM cte
)
SELECT
    month,
    monthly_revenue,
    previous_month_revenue,
    monthly_revenue - previous_month_revenue AS revenue_change,
    ((monthly_revenue - previous_month_revenue)
        / NULLIF(previous_month_revenue, 0)) * 100
        AS growth_percentage
FROM growth
ORDER BY month;

