/* Q18. Customers With Increasing Order Activity
Find customers whose last order value is greater than their
first order value.

Return:
- customer_id
- first_order_value
- last_order_value
- increase_amount */
WITH order_values AS (
    SELECT 
        o.customer_id,
        o.order_id,
        o.order_date,
        SUM(po.quantity * po.unit_price) AS order_value
    FROM orders o
    JOIN product_orders po
        ON o.order_id = po.order_id
    GROUP BY 
        o.customer_id,
        o.order_id,
        o.order_date
),

ranked AS (
    SELECT *,
        ROW_NUMBER() OVER (
            PARTITION BY customer_id 
            ORDER BY order_date ASC, order_id ASC
        ) AS first_order_rank,
        
        ROW_NUMBER() OVER (
            PARTITION BY customer_id 
            ORDER BY order_date DESC, order_id DESC
        ) AS last_order_rank
    FROM order_values
),

customer_orders AS (
    SELECT 
        customer_id,
        MAX(CASE 
            WHEN first_order_rank = 1 
            THEN order_value 
        END) AS first_order_value,
        
        MAX(CASE 
            WHEN last_order_rank = 1 
            THEN order_value 
        END) AS last_order_value
    FROM ranked
    GROUP BY customer_id
)

SELECT 
    customer_id,
    first_order_value,
    last_order_value,
    last_order_value - first_order_value AS increase_amount
FROM customer_orders
WHERE last_order_value > first_order_value;

