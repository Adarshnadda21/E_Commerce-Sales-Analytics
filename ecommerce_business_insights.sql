/* Q21. Customers Spending Above Average
Find customers whose total revenue is greater than the
average revenue of all customers who have placed orders.

Show:
- customer_id
- customer_name
- total_revenue */

SELECT
    c.customer_id,
    CONCAT(c.first_name, ' ', c.last_name) AS customer_name,
    SUM(po.quantity * po.unit_price) AS total_revenue
FROM customers c
JOIN orders o
