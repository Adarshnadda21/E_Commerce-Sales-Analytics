/* Q1. Customer Revenue Analysis
Find every customer who has placed at least one order.
Show:
- customer_id
- customer name
- number of orders
- total quantity purchased
- total revenue
Sort by total revenue from highest to lowest. */

select c.customer_id,concat(c.first_name,' ' ,c.last_name) as customer_name, count(distinct o.order_id) as total_orders , 
sum(po.quantity) as total_quantity , sum(po.unit_price *po.quantity) as total_revenue from customers c
join orders o
on c.customer_id=o.customer_id
join product_orders po
on o.order_id=po.order_id 
group by c.customer_id,customer_name 
having count(o.order_id) >=1
order by total_revenue desc;


