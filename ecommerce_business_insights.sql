/* Q9. Running Monthly Revenue
Calculate total revenue for each month and the cumulative
(running) revenue over time.
Show:
- month
- monthly_revenue
- cumulative_revenue */
WITH monthly_revenue AS (
    SELECT
        DATE_FORMAT(o.order_date, '%Y-%m') AS month,
        SUM(po.quantity * po.unit_price) AS monthly_revenue
    FROM orders o
    JOIN product_orders po
        ON o.order_id = po.order_id
    GROUP BY DATE_FORMAT(o.order_date, '%Y-%m')
)
SELECT
    month,
    monthly_revenue,
    SUM(monthly_revenue) OVER (
        ORDER BY month
    ) AS cumulative_revenue
FROM monthly_revenue
ORDER BY month;

