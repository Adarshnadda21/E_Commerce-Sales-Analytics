/* Q24. Customers With At Least 3 Orders
Find customers who have placed at least 3 orders.
Return customer details and their order count.
Use a subquery to identify qualifying customers. */

SELECT 
    c.customer_id,
    CONCAT(c.first_name, ' ', c.last_name) AS customer_name,
    c.city,
    c.state_province,
    t.total_orders
FROM customers c
JOIN (
    SELECT 
        customer_id,
        COUNT(order_id) AS total_orders
    FROM orders
    GROUP BY customer_id
    HAVING COUNT(order_id) >= 3
) AS t
    ON c.customer_id = t.customer_id;




/* Q25. Customers Who Bought a Specific Product Type
Find customers who have purchased at least one product from
the 'oven' product type.
Show each customer only once. */
