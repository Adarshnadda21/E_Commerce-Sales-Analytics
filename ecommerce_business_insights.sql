(
    SELECT AVG(total_revenue)
    FROM (
        SELECT
            o.customer_id,
            SUM(po.quantity * po.unit_price) AS total_revenue
        FROM orders o
        JOIN product_orders po
            ON o.order_id = po.order_id
        GROUP BY o.customer_id
    ) AS t
);

