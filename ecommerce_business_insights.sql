/* Q12. Order Contribution to Customer Revenue
For every order, calculate:
- order value
- customer's total revenue
- percentage of customer revenue contributed by that order
Use a window function to calculate the customer total. */
WITH cte AS (
    SELECT
        customer_id,
        order_id,
        order_value,
        SUM(order_value) OVER (
            PARTITION BY customer_id
        ) AS customer_total_revenue
    FROM (
        SELECT
            o.customer_id,
            o.order_id,
            SUM(po.quantity * po.unit_price) AS order_value
        FROM orders o
        JOIN product_orders po
            ON o.order_id = po.order_id
        GROUP BY o.customer_id, o.order_id
    ) AS t
)
SELECT
    customer_id,
    order_id,
    order_value,
    customer_total_revenue,
    (order_value / customer_total_revenue) * 100
        AS percentage_of_customer_revenue
FROM cte;


/* Q13. Highest-Value Order for Every Customer
