/* Q26. Second-Highest Revenue Product
Find the product with the second-highest total revenue.

Use a subquery rather than LIMIT/OFFSET. */

WITH cte AS (
    SELECT
        p.product_id,
        p.product_name,
        SUM(po.quantity * po.unit_price) AS total_revenue
    FROM products p
    JOIN product_orders po
        ON p.product_id = po.product_id
    GROUP BY
        p.product_id,
        p.product_name
)
SELECT
    product_id,
    product_name,
    total_revenue AS second_highest_revenue
FROM cte
WHERE total_revenue = (
    SELECT MAX(total_revenue)
    FROM cte
    WHERE total_revenue < (
        SELECT MAX(total_revenue)
        FROM cte
    )
);
 
 
